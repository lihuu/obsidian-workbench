import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import esbuildSvelte from "esbuild-svelte";
import { sveltePreprocess } from "svelte-preprocess";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	platform: "browser",
	mainFields: ["svelte", "browser", "module", "main"],
	conditions: ["svelte", "browser"],
	define: {
		"process.env.NODE_ENV": prod ? '"production"' : '"development"',
	},
	plugins: [
		esbuildSvelte({
			compilerOptions: {
				dev: !prod,
				css: "external",
			},
			preprocess: sveltePreprocess(),
		}),
	],
});

// Desktop-only embedded Runner. It is loaded lazily by the plugin on desktop
// and never imported into the mobile bundle.
const runnerContext = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["runner/server.mjs"],
	bundle: true,
	external: [...builtinModules, ...builtinModules.map((name) => `node:${name}`)],
	format: "cjs",
	target: "node20",
	logLevel: "info",
	sourcemap: false,
	treeShaking: true,
	outfile: "runner.cjs",
	minify: prod,
	platform: "node",
});

if (prod) {
	await Promise.all([context.rebuild(), runnerContext.rebuild()]);
	await Promise.all([context.dispose(), runnerContext.dispose()]);
} else {
	await Promise.all([context.watch(), runnerContext.watch()]);
}
